-- ─── triggers updated_at ──────────────────────────────────────────────────────
do $$
declare
  t text;
begin
  foreach t in array array[
    'users', 'listings', 'listing_photos', 'reservations', 'conversations', 'messages',
    'host_payouts', 'reviews', 'guest_reviews', 'admin_notes', 'host_documents',
    'client_reports', 'activity_logs'
  ]
  loop
    execute format(
      'create trigger %I before update on public.%I for each row execute function public.set_updated_at()',
      t || '_set_updated_at', t
    );
  end loop;
end;
$$;

-- ─── Sécurité : seule l'API Next.js (clé secrète) lit et écrit ces tables ─────
do $$
declare
  t text;
begin
  foreach t in array array[
    'users', 'password_reset_tokens', 'listings', 'listing_photos', 'reservations',
    'conversations', 'messages', 'host_payouts', 'reviews', 'guest_reviews',
    'admin_notes', 'host_documents', 'client_reports', 'activity_logs'
  ]
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon, authenticated', t);
  end loop;
end;
$$;

revoke execute on function public.set_updated_at() from anon, authenticated, public;

